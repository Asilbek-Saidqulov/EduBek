def deep_merge(base, overlay):
    out = dict(base)
    for k, v in overlay.items():
        if isinstance(v, dict) and isinstance(out.get(k), dict):
            out[k] = deep_merge(out[k], v)
        else:
            out[k] = v
    return out


def count_keys(obj):
    n = 0
    for v in obj.values():
        n += 1
        if isinstance(v, dict):
            n += count_keys(v)
    return n


