function countKeys(obj) {
  let count = 0;
  for (const k of Object.keys(obj)) {
    count += 1;
    const v = obj[k];
    if (v && typeof v === "object" && !Array.isArray(v)) {
      count += countKeys(v);
    }
  }
  return count;
}

