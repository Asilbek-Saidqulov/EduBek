    with open(path, "r", encoding="utf-8") as f:
        data = json.load(f)
    data["organizationPlatform"] = content
    with open(path, "w", encoding="utf-8") as f:
        json.dump(data, f, ensure_ascii=False, indent=2)
        f.write("\n")
    count = count_keys(content)
    print(f"  {locale_file}: organizationPlatform added ({count} keys)")

