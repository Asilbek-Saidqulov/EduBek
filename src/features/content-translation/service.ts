/**
 * Build multilingual metadata for a resource. This is the additive
 * enrichment that gets attached to resource DTOs so the frontend
 * knows what languages are available and what the translation state is.
 */
export async function buildMultilingualMetadata(
  resourceId: string,
  defaultLanguage: string,
  requestedLanguage?: string,
): Promise<MultilingualMetadata> {
  const translations = await repo.findResourceTranslations(resourceId);
  const availableLanguages = translations.map((t: any) => t.language);
  // Include the default language even if there's no explicit translation row
  if (!availableLanguages.includes(defaultLanguage)) {
    availableLanguages.unshift(defaultLanguage);
  }

  const currentLanguage = requestedLanguage ?? defaultLocale;
  const currentTranslation = translations.find(
    (t: any) => t.language === currentLanguage,
  );

  const isTranslated = currentLanguage !== defaultLanguage && !!currentTranslation;
  const translationStatus = currentTranslation
    ? (currentTranslation.translationStatus as TranslationStatus)
    : currentLanguage === defaultLanguage
      ? "published" as TranslationStatus
      : "missing" as TranslationStatus;

  return {
    defaultLanguage,
    availableLanguages,
    currentLanguage,
    isTranslated,
    translationStatus,
    canTranslate: true, // AI translation is always available
    translatedBy: currentTranslation?.translatedBy ?? null,
    translationProvider: (currentTranslation?.translationProvider as TranslationProvider) ?? null,
    translationVersion: currentTranslation?.translationVersion ?? 0,
    translatedAt: currentTranslation?.translatedAt
      ? currentTranslation.translatedAt.toISOString()
      : null,
  };
}

