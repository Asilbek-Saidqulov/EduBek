export async function getResourceTranslations(
  ctx: AuthContext,
  resourceId: string,
): Promise<ResourceTranslationDto[]> {
  if (!ctx.userId) throw unauthorized("Authentication required");
  const translations = await repo.findResourceTranslations(resourceId);
  return translations.map(mapResourceTranslation);
}

export async function getResourceTranslation(
  ctx: AuthContext,
  resourceId: string,
  language: string,
): Promise<ResourceTranslationDto> {
  if (!ctx.userId) throw unauthorized("Authentication required");
  const translation = await repo.findResourceTranslation(resourceId, language);
  if (!translation) throw notFound("Translation not found");
  return mapResourceTranslation(translation);
}

export async function createResourceTranslation(
  ctx: AuthContext,
  resourceId: string,
  input: {
    language: string;
    title: string;
    description?: string;
    content?: string;
    translationStatus?: TranslationStatus;
    translationProvider?: TranslationProvider;
    isAutoGenerated?: boolean;
    slug?: string;
  },
): Promise<ResourceTranslationDto> {
  if (!ctx.userId) throw unauthorized("Authentication required");
  // Verify resource exists and caller has access
  const resource = await db.resource.findUnique({
    where: { id: resourceId },
    select: { id: true, ownerId: true, title: true, language: true },
  });
  if (!resource) throw notFound("Resource not found");
  if (resource.ownerId !== ctx.userId && !ctx.isSuperadmin) {
    throw forbidden("Only the resource owner can create translations");
  }
  // Check if translation already exists
  const existing = await repo.findResourceTranslation(resourceId, input.language);
  if (existing) throw badRequest("Translation already exists for this language");

  const translation = await repo.createResourceTranslation({
    resourceId,
    language: input.language,
    title: input.title,
    description: input.description,
    content: input.content,
    translationStatus: input.translationStatus ?? "draft",
    translatedBy: input.isAutoGenerated ? undefined : ctx.userId,
    translationProvider: input.translationProvider,
    isAutoGenerated: input.isAutoGenerated ?? false,
    slug: input.slug,
  });

  log.info("translation.created", { resourceId, language: input.language });
  return mapResourceTranslation(translation);
}

export async function updateResourceTranslation(
  ctx: AuthContext,
  resourceId: string,
  language: string,
  input: {
    title?: string;
    description?: string | null;
    content?: string;
    translationStatus?: TranslationStatus;
    translationProvider?: TranslationProvider;
    translationVersion?: number;
    isAutoGenerated?: boolean;
    slug?: string | null;
  },
): Promise<ResourceTranslationDto> {
  if (!ctx.userId) throw unauthorized("Authentication required");
  const resource = await db.resource.findUnique({
    where: { id: resourceId },
    select: { id: true, ownerId: true },
  });
  if (!resource) throw notFound("Resource not found");
  if (resource.ownerId !== ctx.userId && !ctx.isSuperadmin) {
    throw forbidden("Only the resource owner can update translations");
  }

  const updated = await repo.updateResourceTranslation(resourceId, language, {
    title: input.title,
    description: input.description,
    content: input.content,
    translationStatus: input.translationStatus,
    translationProvider: input.translationProvider,
    translationVersion: input.translationVersion,
    isAutoGenerated: input.isAutoGenerated,
    slug: input.slug,
  });

  return mapResourceTranslation(updated);
}

export async function deleteResourceTranslation(
  ctx: AuthContext,
  resourceId: string,
  language: string,
): Promise<{ resourceId: string; language: string }> {
  if (!ctx.userId) throw unauthorized("Authentication required");
  const resource = await db.resource.findUnique({
    where: { id: resourceId },
    select: { id: true, ownerId: true, language: true },
  });
  if (!resource) throw notFound("Resource not found");
  if (resource.ownerId !== ctx.userId && !ctx.isSuperadmin) {
    throw forbidden("Only the resource owner can delete translations");
  }
  if (resource.language === language) {
    throw badRequest("Cannot delete the default language translation");
  }
  await repo.deleteResourceTranslation(resourceId, language);
  return { resourceId, language };
}

