/**
 * EduBek — Content translation service.
 *
 * Phase 4E.5: Universal translation service for all educational content.
 *
 * Provides:
 *   - Resource translation CRUD (create, read, update, delete)
 *   - Category translation upsert
 *   - Subscription plan translation upsert
 *   - Multilingual metadata builder (for DTO enrichment)
 *   - AI translation integration points
 *
 * Architecture:
 *   Entity → Translation Layer → Language Variants
 *
 * One logical entity. Multiple localized variants.
 * No duplication of IDs, ownership, or relationships.
 */
