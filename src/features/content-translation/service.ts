export async function upsertCategoryTranslation(
  ctx: AuthContext,
  categoryId: string,
  input: {
    language: string;
    name: string;
    description?: string;
    slug?: string;
  },
): Promise<CategoryTranslationDto> {
  if (!ctx.userId) throw unauthorized("Authentication required");
  if (!can(ctx, PersonalPermission.RESOURCE_CREATE) && !ctx.isSuperadmin) {
    throw forbidden("No permission to manage category translations");
  }
  const result = await repo.upsertCategoryTranslation({
    categoryId,
    language: input.language,
    name: input.name,
    description: input.description,
    slug: input.slug,
  });
  return mapCategoryTranslation(result);
}

/**
 * Resolve a category's name for a specific locale.
 * Falls back to the default name if no translation exists.
 */
export async function resolveCategoryName(
  categoryId: string,
  locale: string,
): Promise<string> {
  const translation = await repo.findCategoryTranslation(categoryId, locale);
  if (translation) return translation.name;
  // Fallback to the category's default name
  const category = await db.mpCategory.findUnique({
    where: { id: categoryId },
    select: { name: true },
  });
  return category?.name ?? "Unknown";
}

