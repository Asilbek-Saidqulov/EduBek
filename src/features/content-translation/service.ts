/**
 * Create an AI-generated translation for a resource.
 * This is the integration point for the AI translation pipeline.
 * The actual AI call is made by the caller; this function persists the result.
 */
export async function createAiTranslation(
  ctx: AuthContext,
  resourceId: string,
  language: string,
  translatedContent: {
    title: string;
    description?: string;
    content: string;
  },
): Promise<ResourceTranslationDto> {
  if (!ctx.userId) throw unauthorized("Authentication required");
  const resource = await db.resource.findUnique({
    where: { id: resourceId },
    select: { id: true, ownerId: true, language: true },
  });
  if (!resource) throw notFound("Resource not found");
  if (resource.ownerId !== ctx.userId && !ctx.isSuperadmin) {
    throw forbidden("Only the resource owner can create AI translations");
  }
  if (resource.language === language) {
    throw badRequest("Cannot translate to the same language as the original");
  }

  // Check if a translation already exists — if so, update it
  const existing = await repo.findResourceTranslation(resourceId, language);
  if (existing) {
    const updated = await repo.updateResourceTranslation(resourceId, language, {
      title: translatedContent.title,
      description: translatedContent.description,
      content: translatedContent.content,
      translationStatus: "published",
      translationProvider: "ai",
      translationVersion: existing.translationVersion + 1,
      isAutoGenerated: true,
    });
    log.info("ai_translation.updated", { resourceId, language, version: existing.translationVersion + 1 });
    return mapResourceTranslation(updated);
  }

  const translation = await repo.createResourceTranslation({
    resourceId,
    language,
    title: translatedContent.title,
    description: translatedContent.description,
    content: translatedContent.content,
    translationStatus: "published",
    translationProvider: "ai",
    isAutoGenerated: true,
  });

  log.info("ai_translation.created", { resourceId, language });
  return mapResourceTranslation(translation);
}
