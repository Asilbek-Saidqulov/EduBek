// Mappers
// ---------------------------------------------------------------------------

function safeParse<T>(raw: string | null, fallback: T): T {
  if (!raw) return fallback;
  try { return JSON.parse(raw) as T; } catch { return fallback; }
}

function mapResourceTranslation(t: any): ResourceTranslationDto {
  return {
    id: t.id,
    resourceId: t.resourceId,
    language: t.language,
    title: t.title,
    description: t.description,
    content: t.content,
    translationStatus: t.translationStatus as TranslationStatus,
    translatedBy: t.translatedBy,
    translationProvider: t.translationProvider as TranslationProvider | null,
    translationVersion: t.translationVersion,
    translatedAt: t.translatedAt ? t.translatedAt.toISOString() : null,
    isAutoGenerated: t.isAutoGenerated,
    slug: t.slug,
    createdAt: t.createdAt.toISOString(),
    updatedAt: t.updatedAt.toISOString(),
  };
}

function mapCategoryTranslation(t: any): CategoryTranslationDto {
  return {
    id: t.id,
    categoryId: t.categoryId,
    language: t.language,
    name: t.name,
    description: t.description,
    slug: t.slug,
    createdAt: t.createdAt.toISOString(),
    updatedAt: t.updatedAt.toISOString(),
  };
}

function mapPlanTranslation(t: any): PlanTranslationDto {
  return {
    id: t.id,
    planId: t.planId,
    language: t.language,
    name: t.name,
    description: t.description,
    features: safeParse(t.features, null),
    createdAt: t.createdAt.toISOString(),
    updatedAt: t.updatedAt.toISOString(),
  };
}

